const {readFileSync}=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const path=require('node:path'),root=path.join(__dirname,'..'),html=readFileSync(path.join(root,'app.html'),'utf8');
const ctx=vm.createContext({console,uuid:require('node:crypto').randomUUID,validDate:s=>/^\d{4}-\d{2}-\d{2}$/.test(s),iso:d=>[d.getFullYear(),String(d.getMonth()+1).padStart(2,'0'),String(d.getDate()).padStart(2,'0')].join('-'),itemById:(d,id)=>d.items.find(i=>i.id===id),isRecurringTodo:i=>i.type==='Todo'&&!!i.recurrence,dateSerial:d=>Date.UTC(d.getFullYear(),d.getMonth(),d.getDate())/86400000});
vm.runInContext(html.slice(html.indexOf('function* regularOccurrences'),html.indexOf('function* recurrenceOccurrences')),ctx);
const model=vm.runInContext(readFileSync(path.join(root,'planner-model.js'),'utf8')+'\nPlannerModel',ctx);
const item={id:'a',type:'Todo',status:'Todo',scheduledDates:[],recurrence:{frequency:'daily',interval:2,startDate:'2026-12-28'}},db={items:[item],archiveIndex:[]};
const id=model.session(db,item,'2026-12-28',480,15,'2026-12-28');
model.repeat(db,id);
assert.equal(model.sessions(db,'2026-12-29').length,0);
const block=model.sessions(db,'2026-12-30')[0];
model.change(db,block,{date:'2026-12-31',done:true});
assert.equal(model.sessions(db,'2026-12-30').length,0);
assert.equal(model.sessions(db,'2026-12-31')[0].occurrence,'2026-12-30');
assert.equal(item.status,'Todo');
model.change(db,model.sessions(db,'2027-01-01')[0],{start:600},true);
assert.equal(model.sessions(db,'2026-12-28')[0].start,480);
assert.equal(model.sessions(db,'2027-01-03')[0].start,600);
item.archived=true;model.reconcile(db,'2027-01-01',700);
assert.equal(model.sessions(db,'2027-01-03').length,0);
assert.equal(model.sessions(db,'2027-01-01').length,1);
item.archived=false;model.reconcile(db,'2027-01-02',0);
assert.equal(model.sessions(db,'2027-01-03').length,0);
console.log('PASS session identities, dated rules, moved exceptions, history and archival');
const meetings=vm.runInContext('PlannerMeetings',ctx);
const zone='Europe/Amsterdam';
assert.equal(new Date(meetings.wall('2026-10-25',150,zone)).toISOString(),'2026-10-25T00:30:00.000Z');
assert.equal(new Date(meetings.wall('2026-03-29',150,zone)).toISOString(),'2026-03-29T01:30:00.000Z');
const m={title:'Meeting',content:'Shared',exceptions:{},versions:[{from:'2026-03-25',date:'2026-03-25',start:540,end:570,zone,enabled:true,recurrence:{frequency:'daily',startDate:'2026-03-25',interval:1}}]};
assert.equal(meetings.blocks(m,'m','2026-03-27','Europe/Istanbul')[0].start,660);
assert.equal(meetings.blocks(m,'m','2026-03-30','Europe/Istanbul')[0].start,600);
m.versions[0].allDay=true;m.versions[0].span=2;m.versions[0].recurrence=null;
assert.equal(meetings.blocks(m,'m','2026-03-26',zone).length,1);
assert.equal(meetings.blocks(m,'m','2026-03-27',zone).length,0);
console.log('PASS meeting wall times, DST transitions and exclusive all-day ends');

// Navigation is a pure projection, including moved exceptions and ongoing work.
const navDb={planner:{sessions:{ongoing:{item:'x',date:'2026-12-28',start:590,duration:30},past:{item:'x',date:'2026-12-28',start:570,duration:30},future:{item:'x',date:'2027-01-01',start:600,duration:30},done:{item:'x',date:'2027-01-02',start:600,duration:30,done:true}},rules:{series:{item:'x',versions:[{from:'2026-12-28',enabled:true,offset:0,start:600,duration:30,recurrence:{frequency:'daily',interval:2,startDate:'2026-12-28'}}],exceptions:{'2026-12-28':{removed:true},'2026-12-30':{date:'2026-12-29'},'2027-01-01':{done:true}}}}}};
const navBefore=JSON.stringify(navDb),nav=model.upcoming(navDb,'2026-12-28',600).get('x');
assert.equal(nav.length,3);assert.equal(nav[0].key,'ongoing');assert.equal(nav[1].date,'2026-12-29');assert.equal(nav[1].origin,'2026-12-30');assert.equal(nav[2].key,'future');assert.equal(JSON.stringify(navDb),navBefore);
assert.equal(model.upcoming(navDb,'2027-01-02',600).get('x')[0].date,'2027-01-03');
console.log('PASS read-only upcoming index, ongoing boundaries, completed sessions and moved repeating exceptions');
